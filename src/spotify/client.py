"""Thin wrapper around spotipy for OAuth, track search, and playlist creation.

Credentials come from .env (SPOTIFY_CLIENT_ID, SPOTIFY_CLIENT_SECRET,
SPOTIFY_REDIRECT_URI) -- see FINALSTEPS.md for where to get them. The OAuth
token is cached to .spotify_token_cache (gitignored) so the browser auth flow
only needs to run once per machine.
"""
from __future__ import annotations

import logging
import os
from dataclasses import dataclass

import spotipy
from spotipy.oauth2 import SpotifyOAuth

from src.curator.playlist_agent import CuratedTrack

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger(__name__)

SCOPES = "playlist-modify-public playlist-modify-private"
TOKEN_CACHE_PATH = ".spotify_token_cache"


class SpotifyCredentialsError(RuntimeError):
    pass


@dataclass
class PushResult:
    playlist_id: str
    playlist_url: str
    added_track_ids: list[str]
    skipped_tracks: list[str]  # human-readable "artist - name" strings that couldn't be matched


def _require_env(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise SpotifyCredentialsError(
            f"Missing {name} in the environment. Copy .env.example to .env and fill in your "
            "Spotify Developer Dashboard credentials -- see FINALSTEPS.md."
        )
    return value


def get_spotify_client() -> spotipy.Spotify:
    client_id = _require_env("SPOTIFY_CLIENT_ID")
    client_secret = _require_env("SPOTIFY_CLIENT_SECRET")
    redirect_uri = _require_env("SPOTIFY_REDIRECT_URI")

    auth_manager = SpotifyOAuth(
        client_id=client_id,
        client_secret=client_secret,
        redirect_uri=redirect_uri,
        scope=SCOPES,
        cache_path=TOKEN_CACHE_PATH,
    )
    return spotipy.Spotify(auth_manager=auth_manager)


def search_track(sp: spotipy.Spotify, artist: str, name: str) -> str | None:
    """Returns a Spotify track URI, or None if no confident match was found."""
    query = f"track:{name} artist:{artist}"
    try:
        results = sp.search(q=query, type="track", limit=1)
    except Exception as exc:
        log.warning("Spotify search failed for %r: %s", query, exc)
        return None

    items = results.get("tracks", {}).get("items", [])
    if not items:
        return None
    return items[0]["uri"]


def create_playlist_from_tracks(
    sp: spotipy.Spotify,
    playlist_name: str,
    tracks: list[CuratedTrack],
    description: str = "Generated by the music-agent curator",
    public: bool = False,
) -> PushResult:
    me = sp.current_user()
    playlist = sp.user_playlist_create(
        user=me["id"], name=playlist_name, public=public, description=description
    )

    uris: list[str] = []
    skipped: list[str] = []
    for track in tracks:
        uri = search_track(sp, track.artist, track.name)
        if uri is None:
            log.info("Skipping unmatched track: %s - %s", track.artist, track.name)
            skipped.append(f"{track.artist} - {track.name}")
            continue
        uris.append(uri)

    if uris:
        # Spotify caps add-to-playlist at 100 URIs per call.
        for i in range(0, len(uris), 100):
            sp.playlist_add_items(playlist["id"], uris[i : i + 100])

    return PushResult(
        playlist_id=playlist["id"],
        playlist_url=playlist["external_urls"]["spotify"],
        added_track_ids=uris,
        skipped_tracks=skipped,
    )
